  methodName,
  systemConvention,
  personName,
  birthDate,
  displayNumber,
  engineVersion,
  coreSummaryCards,
  detailedCalculations,
  karmicDebts,
  calculationBreakdown,
  strengths,
  challenges,
  careerTendencies,
  financialTendencies,
  loveThemes,
  compatibility,
  cyclesOrForecast,
