"use client";

import React, { useState } from "react";
import {
  Printer,
  Download,
  Loader2,
  Calendar,
  User,
  ShieldCheck,
  Compass,
  Sparkles,
  TrendingUp,
  Heart,
  DollarSign,
  AlertCircle,
  Clock,
  Layers,
  Flame,
} from "lucide-react";

